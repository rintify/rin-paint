export const STANDARD_FONTS = [{ id: 'sans', name: 'ゴシック' }, { id: 'serif', name: '明朝' }, { id: 'mono', name: '等幅' }];
export function fontFamily(id: string): string {
  if (id === 'sans') return '"Hiragino Kaku Gothic ProN", "Yu Gothic", sans-serif';
  if (id === 'serif') return '"Hiragino Mincho ProN", "Yu Mincho", serif';
  if (id === 'mono') return '"MS Gothic", monospace';
  return `"rin-font-${id.replace(/[^a-zA-Z0-9-]/g, '')}"`;
}
let loadedFonts: ProjectFont[] = [];
let fontSheet: HTMLStyleElement | null = null;
let fontEpoch = 0;
export async function loadFonts(fonts: ProjectFont[]): Promise<void> {
  const epoch = ++fontEpoch;
  loadedFonts = fonts;
  fontSheet ??= document.head.appendChild(document.createElement('style'));
  fontSheet.textContent = fontCss(fonts);
  await Promise.all(fonts.map(f => document.fonts.load(`16px ${fontFamily(f.id)}`)));
  if (epoch !== fontEpoch) return;
}
function fontCss(fonts = loadedFonts): string {
  return fonts.map(f => `@font-face{font-family:${fontFamily(f.id)};src:url("${f.dataUrl.replace(/["\n\r]/g, '')}");}`).join('\n');
}
function applyStyle(el: HTMLElement, style: TextStyle, ppi: number): void {
  el.style.fontFamily = fontFamily(style.fontId);
  el.style.fontSize = `${style.sizeMm * ppi / 25.4}px`;
  el.style.color = style.color;
}
export function styleTextRoot(el: HTMLElement, text: TextParams, ppi: number): void {
  const alignment = textAlignment(text);
  Object.assign(el.style, {
    writingMode: text.direction === 'vertical' ? 'vertical-rl' : 'horizontal-tb',
    textOrientation: 'mixed', whiteSpace: 'pre-wrap', overflowWrap: 'anywhere', wordBreak: 'normal',
    lineBreak: 'strict', lineHeight: String(text.lineHeight), boxSizing: 'border-box',
    width: text.width === null ? 'max-content' : `${text.width}px`,
    height: text.height === null ? 'max-content' : `${text.height}px`,
    minWidth: '1em', minHeight: '1em', padding: '0', margin: '0', border: '0',
    overflow: text.width === null && text.height === null ? 'visible' : 'hidden',
    textAlign: alignment.textAlign,
    alignContent: alignment.alignContent,
  });
  applyStyle(el, text.style, ppi);
}
/** Shared DOM for editable text and its composited bitmap. */
export function populateText(el: HTMLElement, text: TextParams, ppi: number): void {
  styleTextRoot(el, text, ppi);
  const fragment = document.createDocumentFragment();
  const points = [...new Set([0, text.content.length, ...text.ranges.flatMap(r => [r.start, r.end]), ...text.ruby.flatMap(r => [r.start, r.end])])].sort((a, b) => a - b);
  let rubyEl: HTMLElement | null = null;
  for (let i = 0; i < points.length - 1; i++) {
    const start = points[i], end = points[i + 1];
    const ruby = text.ruby.find(r => r.start <= start && r.end > start);
    if (ruby?.start === start) {
      rubyEl = document.createElement('ruby');
      rubyEl.style.rubyPosition = 'over';
      fragment.append(rubyEl);
    }
    const span = document.createElement('span');
    span.textContent = text.content.slice(start, end);
    applyStyle(span, styleAt(text, start), ppi);
    (rubyEl ?? fragment).append(span);
    if (ruby && ruby.end === end && rubyEl) {
      const rt = document.createElement('rt');
      rt.textContent = ruby.text;
      rt.contentEditable = 'false';
      applyStyle(rt, styleAt(text, ruby.start), ppi);
      rt.style.fontSize = `${styleAt(text, ruby.start).sizeMm * ppi / 50.8}px`;
      rt.style.userSelect = 'none';
      rubyEl.append(rt);
      rubyEl = null;
    }
  }
  if (!text.content || text.content.endsWith('\n')) {
    const br = document.createElement('br');
    br.dataset.placeholder = 'true';
    fragment.append(br);
  }
  el.replaceChildren(fragment);
}

interface Cache { key:string; layout:CanvasTextLayout|null; metadata:HTMLCanvasElement; ready:Promise<void>; error?:unknown }
/** Layout stays editable; text pixels are generated by Canvas 2D inside bounded render tiles. */
export class TextRenderer {
  private cache=new Map<string,Cache>();
  clear():void {for(const entry of this.cache.values()) previewCache.delete(entry);this.cache.clear();}
  retain(ids:Set<string>):void {for(const id of this.cache.keys()) if(!ids.has(id)){previewCache.delete(this.cache.get(id)!);this.cache.delete(id);}}
  get(id:string):HTMLCanvasElement|null {
    const item=this.cache.get(id);if(!item) return null;
    const existing=previewCache.get(item);if(existing) return existing;
    if(!item.layout) return item.metadata;
    const layout=item.layout,scale=Math.min(1,512/Math.max(layout.width,layout.height));
    const canvas=document.createElement('canvas');canvas.width=Math.max(1,Math.ceil(layout.width*scale));canvas.height=Math.max(1,Math.ceil(layout.height*scale));
    Object.assign(canvas.dataset,item.metadata.dataset);
    const ctx=canvas.getContext('2d')!;ctx.scale(scale,scale);drawCanvasText(ctx,layout);
    previewCache.set(item,canvas,canvas.width*canvas.height*4);return canvas;
  }
  request(id:string,text:TextParams,ppi:number,onReady:()=>void):void {
    const key=JSON.stringify([{...text,x:0,y:0},ppi,fontEpoch]);
    if(this.cache.get(id)?.key===key) return;
    const metadata=document.createElement('canvas');metadata.width=metadata.height=1;
    const item:Cache={key,layout:null,metadata,ready:Promise.resolve()};
    const old=this.cache.get(id);if(old)previewCache.delete(old);this.cache.set(id,item);
    item.ready=(async()=>{
      const host=document.createElement('div');
      Object.assign(host.style,{position:'fixed',left:'-100000px',top:'0',pointerEvents:'none',boxSizing:'border-box',display:'flow-root'});
      const node=document.createElement('div');populateText(node,text,ppi);host.append(node);document.body.append(host);
      try {
        const families=new Set([text.style.fontId,...text.ranges.map(range=>range.fontId)]);
        await Promise.all([...families].map(id=>document.fonts.load(`16px ${fontFamily(id)}`)));
        if(this.cache.get(id)!==item) return;
        item.layout=measureCanvasText(node,text,ppi);
        Object.assign(metadata.dataset,{textWidth:String(item.layout.width),textHeight:String(item.layout.height),
          textOffsetX:String(item.layout.offsetX),textOffsetY:String(item.layout.offsetY),textPadding:'0'});
        onReady();
      } catch(error) {if(this.cache.get(id)===item)item.error=error;} finally {host.remove();}
    })();
  }
  async ready():Promise<void> {
    let entries:Cache[];
    do {entries=[...this.cache.values()];await Promise.all(entries.map(entry=>entry.ready));}
    while([...this.cache.values()].some(entry=>!entries.includes(entry)));
    if([...this.cache.values()].some(entry=>entry.error)) throw new Error('文字の描画に失敗しました。フォントまたは文字枠を確認してください。');
  }
  draw(ctx:CanvasRenderingContext2D,id:string,text:TextParams):void {
    const layout=this.cache.get(id)?.layout;if(!layout)return;
    ctx.save();composeCanvasTransform(ctx,1,0,0,1,text.x+layout.width/2,text.y+layout.height/2);ctx.rotate(text.rotation??0);
    ctx.translate(-layout.width/2,-layout.height/2);
    if(text.width!==null||text.height!==null){ctx.beginPath();ctx.rect(0,0,layout.width,layout.height);ctx.clip();}
    drawCanvasText(ctx,layout);ctx.restore();
  }
}
